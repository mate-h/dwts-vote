#!/usr/bin/env node
// Download DWTS seasons from Wikipedia and bundle them with the app (src/lib/episodes/sNN.json).
//
//   node scripts/fetch-episode.mjs --season 35         # refresh one season (e.g. the one airing now)
//   node scripts/fetch-episode.mjs --season 30-35      # a range (or a list: --season 1,5,34)
//   node scripts/fetch-episode.mjs --all               # every season from 1 until Wikipedia has no article
//   node scripts/fetch-episode.mjs --season 35 --list  # show each week's status, write nothing
//   node scripts/fetch-episode.mjs --season 35 --dry-run
//
// Each file holds the season's week list (aired or upcoming) and a ballot for every aired week.
// Then rebuild/redeploy: npm run build (LAN) or npm run cf:deploy (Cloudflare).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { fetchSeasonPage, parseSeason, sourceOf, showTime, WikiError } from '../src/lib/server/wiki.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'src/lib/episodes');

const args = process.argv.slice(2);
const flag = (name) => args.includes('--' + name);
const opt = (name) => {
	const i = args.indexOf('--' + name);
	return i >= 0 ? args[i + 1] : undefined;
};
if (flag('help') || (!opt('season') && !flag('all'))) {
	console.log(fs.readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').slice(1, 11).map((l) => l.replace(/^\/\/ ?/, '')).join('\n'));
	process.exit(flag('help') ? 0 : 1);
}

function parseRange(spec) {
	const out = new Set();
	for (const part of String(spec).split(',')) {
		const [a, b] = part.split('-').map(Number);
		if (!Number.isInteger(a)) throw new Error('bad --season ' + spec);
		for (let n = a; n <= (Number.isInteger(b) ? b : a); n++) out.add(n);
	}
	return [...out];
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let failed = 0;
const seasons = flag('all') ? Array.from({ length: 99 }, (_, i) => i + 1) : parseRange(opt('season'));
for (const season of seasons) {
	let page;
	try {
		page = await fetchSeasonPage(season);
	} catch (e) {
		if (e instanceof WikiError && e.code === 'missing' && flag('all')) break; // past the latest season
		failed++;
		console.error(`season ${season}: ${e.message}`);
		continue;
	}
	const { weeks, episodes } = parseSeason(page.wikitext, season);
	const ready = weeks.filter((w) => w.status === 'ready');
	const summary = `season ${season}: ${ready.filter((w) => w.aired).length}/${weeks.length} weeks aired${ready.some((w) => !w.aired) ? `, line-up out for week ${ready.filter((w) => !w.aired).map((w) => w.week).join(', ')}` : ''}${weeks.some((w) => w.status === 'error') ? ' (errors: ' + weeks.filter((w) => w.error).map((w) => `week ${w.week}: ${w.error}`).join('; ') + ')' : ''}`;
	if (flag('list')) {
		console.log(`${summary} — ${page.title}`);
		for (const w of weeks) console.log(`  week ${w.week}: ${w.night || '(no theme)'}${w.airDate ? ' (' + w.airDate + ')' : ''} — ${w.status === 'ready' ? w.couples + ' couples' + (w.aired ? '' : ' (line-up, not aired)') : w.status}`);
		continue;
	}
	const data = {
		season,
		source: sourceOf(page),
		// ready: aired · lineup: performance order announced, not aired yet · upcoming: nothing yet
		// airsAt: 8 PM Eastern on the episode's air date (when known)
		weeks: weeks.map(({ week, night, status, aired, airDate }) => ({ week, night, status: status !== 'ready' ? 'upcoming' : aired ? 'ready' : 'lineup', ...(airDate ? { airsAt: showTime(airDate) } : {}) })),
		episodes: ready.map((w) => episodes[w.week])
	};
	if (flag('dry-run')) { process.stdout.write(JSON.stringify(data, null, '\t') + '\n'); continue; }
	fs.mkdirSync(OUT_DIR, { recursive: true });
	const file = path.join(OUT_DIR, `s${String(season).padStart(2, '0')}.json`);
	fs.writeFileSync(file, JSON.stringify(data) + '\n');
	console.log(`wrote ${path.relative(ROOT, file)} — ${summary}`);
	if (seasons.length > 1) await sleep(300); // be gentle with the Wikipedia API
}
if (!flag('dry-run') && !flag('list')) writeIndex();
process.exit(failed ? 1 : 0);

// src/lib/episodes/index.js statically imports every season file, so the server bundles them under
// both Vite and wrangler (the Durable Object is bundled outside Vite, without import.meta.glob).
function writeIndex() {
	const names = fs.readdirSync(OUT_DIR).filter((f) => /^s\d+\.json$/.test(f)).sort();
	const lines = names.map((f, i) => `import s${i} from './${f}' with { type: 'json' };`);
	const body = `// Generated by scripts/fetch-episode.mjs — do not edit.\n${lines.join('\n')}\n\nexport default [${names.map((_, i) => 's' + i).join(', ')}];\n`;
	fs.writeFileSync(path.join(OUT_DIR, 'index.js'), body);
}
